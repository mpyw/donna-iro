//! 「もう1回」をどう受け取るか。
//!
//! フィナーレのあと、遊びを続けるかどうかをここで待つ。**声では受けない。**
//! 歓声や物音で勝手に再開してしまうし、そもそも遊び終わったあとに
//! 「続ける」と決めるのは親の仕事なので、意思を持った操作に限る。
//!
//! マウス・キーボード・テレビのリモコンは、供給元が違うだけで意味は同じ。
//! だから口は1つにまとめてある。CEC のリモコン（evdev）を足すときも、
//! `Channel` の送り手をもう1本増やすだけで、ここから下は変わらない。
//!
//! 実装は `io::control`。
//!
//! `Listener`（色を答える）とは別系統にしてある。あちらに混ぜると、
//! フォールバックが「ぜんぶ」に倒れないよう型で塞いだ意図が崩れるため。

pub trait Control: Send {
    /// **遊びを途中でやめたいか。** 待たずにその場で答える。
    ///
    /// 歌っている最中に何度も呼ばれる。押されていたら `true` を返し、
    /// **溜まっているぶんはそこで捨てる**（同じ合図で二度抜けないため）。
    ///
    /// これが真になったら `Game` は鳴っている音を止めて「もう1回」の
    /// 画面へ跳ぶ。**終わりではない。** 親が「この回はここまで」と言った
    /// だけなので、続きを訊く相手はまだ居る。
    ///
    /// 声では受けない理由は `wait_for_again` と同じ。
    fn stop_requested(&mut self) -> bool;

    /// 「もう1回」が来るまで待つ。**押されたら `true`、入力が絶えたら `false`。**
    ///
    /// 待ちに上限は無い。押すのは親なので、テレビの前を離れていれば
    /// いつまででも待つ。
    ///
    /// 読み取りに失敗したときも `false`。**続けられないなら終わりでよい。**
    /// ここで区別しても、親にできることは同じ（もう一度押す）。
    fn wait_for_again(&mut self) -> bool;
}
